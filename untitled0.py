print("\n--- Veri Setindeki Sütunların İsimleri ---")
print(df.columns.tolist())

print("=== TEKRAR EDEN VE EKSİK VERİ ANALİZİ ===")

tekrar_edenler = df[df.duplicated(keep=False)]
