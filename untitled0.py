df = pd.read_csv('spg.csv')

print("=== GÖREV 1: VERİ Ön İşleme ===")

satir_sayisi, sutun_sayisi = df.shape
print(f"Veri Setindeki Toplam Veri Sayısı (Satır): {satir_sayisi}")
